using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Nexus.Core;

namespace Nexus.Compiler
{
    /// <summary>
    /// AOT (Ahead-of-Time) compiler: transpiles Nexus to compilable C#.
    /// Top-level functions become static methods, top-level variables become
    /// static fields, and all remaining top-level statements are wrapped in Main().
    /// Nothing is dropped silently: unhandled nodes emit a comment AND a warning.
    /// </summary>
    public class AotCompiler
    {
        private readonly StringBuilder _sb = new StringBuilder();
        private int _indentLevel;
        private readonly List<string> _errors = new List<string>();
        private readonly List<string> _warnings = new List<string>();
        private bool _inClass;
        private bool _inSwitchCase;
        private readonly Dictionary<string, List<string>> _asmModules = new Dictionary<string, List<string>>();
        private readonly Dictionary<string, string> _asmModuleEntry = new Dictionary<string, string>();
        private readonly HashSet<string> _asmGenerated = new HashSet<string>();

        public List<string> Errors => _errors;
        public List<string> Warnings => _warnings;

        private readonly HashSet<string> _classNames = new HashSet<string>();
        private readonly Dictionary<string, List<string>> _classInitParams =
            new Dictionary<string, List<string>>();
        private readonly Dictionary<string, List<string>> _delegateSignatures =
            new Dictionary<string, List<string>>();
        private readonly Dictionary<string, List<string>> _functionSignatures =
            new Dictionary<string, List<string>>();
        private readonly HashSet<string> _lambdaVars = new HashSet<string>();

        private void ScanCallableSignatures(IEnumerable<Statement> statements)
        {
            foreach (var s in statements)
            {
                switch (s)
                {
                    case DelegateDecl dd:
                        _delegateSignatures[dd.Name] = dd.Parameters
                            .Select(p => string.IsNullOrEmpty(p.Type) ? "dynamic" : p.Type).ToList();
                        break;
                    case FunctionDecl fd when fd.Name != "init" && fd.Name != "constructor":
                        _functionSignatures[fd.Name] = fd.Parameters
                            .Select(p => string.IsNullOrEmpty(p.Type) ? "dynamic" : p.Type).ToList();
                        break;
                    case VariableDecl { Initializer: LambdaExpr } lv:
                        _lambdaVars.Add(lv.Name);
                        break;
                    case NamespaceDecl nd:
                        ScanCallableSignatures(nd.Body);
                        break;
                }
            }
        }

        private void ScanClassTypes(IEnumerable<Statement> statements)
        {
            foreach (var s in statements)
            {
                switch (s)
                {
                    case ClassDecl cd:
                    {
                        _classNames.Add(cd.Name);
                        var ctorP = cd.Members.OfType<FunctionDecl>()
                            .FirstOrDefault(f => f.Name == "init" || f.Name == "constructor");
                        _classInitParams[cd.Name] = ctorP != null
                            ? ctorP.Parameters.Select(p => string.IsNullOrEmpty(p.Type) ? "dynamic" : p.Type).ToList()
                            : new List<string>();
                        break;
                    }
                    case NamespaceDecl nd:
                        ScanClassTypes(nd.Body);
                        break;
                }
            }
        }

        public string CompileToCSharp(ProgramNode program, string namespaceName = "NexusGenerated")
        {
            _sb.Clear();
            _indentLevel = 0;
            _errors.Clear();
            _warnings.Clear();
            _inClass = false;
            _inSwitchCase = false;
            _asmModules.Clear();
            _asmModuleEntry.Clear();
            _asmGenerated.Clear();

            WriteLine("// Generated by Nexus AOT Compiler v1.1");
            WriteLine($"// {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            WriteLine();
            WriteLine("using System;");
            WriteLine("using System.Collections.Generic;");
            WriteLine("using System.Linq;");
            WriteLine();
            WriteLine($"namespace {namespaceName}");
            WriteLine("{");
            _indentLevel++;
            WriteLine("public static class NexusProgram");
            WriteLine("{");
            _indentLevel++;

            GenerateRuntimeHelpers();
            GenerateRegisterSim();

            // Pre-pass: register asm modules so functions declared before the
            // module still get their call sites rewritten
            foreach (var stmt in program.Statements)
            {
                if (stmt is VariableDecl { Initializer: AsmModuleExpr pre } preDecl)
                    RegisterAsmModule(preDecl.Name, pre.Block);
            }

            // Pre-pass: collect class names (constructor-call style) and ctor
            // signatures (default base-chaining when super(...) is omitted)
            _classNames.Clear();
            _classInitParams.Clear();
            _delegateSignatures.Clear();
            _functionSignatures.Clear();
            _lambdaVars.Clear();
            ScanClassTypes(program.Statements);
            ScanCallableSignatures(program.Statements);

            // Partition top level: fields / methods / Main-body
            var mainBody = new List<Statement>();
            foreach (var stmt in program.Statements)
            {
                switch (stmt)
                {
                    case FunctionDecl fd:
                        CompileFunction(fd);
                        break;
                    case VariableDecl vd when vd.Initializer is AsmModuleExpr ame:
                        CompileAsmModule(vd.Name, ame.Block);
                        break;
                    case VariableDecl vd:
                        CompileField(vd);
                        break;
                    case ClassDecl cd:
                        CompileClass(cd);
                        break;
                    case StructDecl sd:
                        CompileStruct(sd);
                        break;
                    case EnumDecl ed:
                        CompileEnum(ed);
                        break;
                    case InteropDeclaration id:
                        CompileInteropDeclaration(id);
                        break;
                    case DelegateDecl dd:
                    {
                        var ps2 = string.Join(", ", dd.Parameters.Select(p =>
                            $"{MapType(string.IsNullOrEmpty(p.Type) || p.Type == "dynamic" ? "object" : p.Type)} {SanitizeName(p.Name)}"));
                        WriteLine($"public delegate {MapType(dd.ReturnType ?? "void")} {SanitizeName(dd.Name)}({ps2});");
                        break;
                    }
                    case EventDecl ed:
                        WriteLine($"public static {SanitizeName(ed.DelegateType)} {SanitizeName(ed.Name)} = null;  // event");
                        break;
                    default:
                        mainBody.Add(stmt);
                        break;
                }
            }

            WriteLine();
            WriteLine("public static void Main()");
            WriteLine("{");
            _indentLevel++;
            foreach (var stmt in mainBody)
                CompileStatement(stmt);
            _indentLevel--;
            WriteLine("}");

            _indentLevel--;
            WriteLine("}");
            _indentLevel--;
            WriteLine("}");

            return _sb.ToString();
        }

        // ================= top-level declarations =================

        private void CompileField(VariableDecl decl)
        {
            // lambda initializers need a delegate type — dynamic rejects lambdas
            var type = decl.Initializer is LambdaExpr lam
                ? LambdaFuncType(lam)
                : TypeForDeclaration(decl);
            var isConst = decl.Modifier == "const" && IsCompileTimeConstant(decl.Initializer);
            string keyword = isConst ? "public const"
                           : (_inClass && !decl.IsStatic) ? "public"
                           : "public static";
            var init = decl.Initializer != null
                ? $" = {CompileExpression(decl.Initializer)}"
                : " = default";
            WriteLine($"{keyword} {type} {SanitizeName(decl.Name)}{init};");
        }

        private void CompileFunction(FunctionDecl decl, bool allowInstance = false)
        {
            // functions with no return statement compile to C# `void` so they
            // convert cleanly to void-returning delegate types (Nexus events)
            var ret = string.IsNullOrEmpty(decl.ReturnType)
                ? (decl.Body.Any(s => s is ReturnStmt) ? "dynamic" : "void")
                : MapType(decl.ReturnType);
            var ps = FormatParams(decl);
            var isStatic = decl.IsStatic || !_inClass || !allowInstance;

            WriteLine();
            WriteLine($"{(isStatic ? "public static" : "public")} {ret} {SanitizeName(decl.Name)}({ps})");
            WriteLine("{");
            _indentLevel++;
            foreach (var s in decl.Body)
                CompileStatement(s);
            if (ret != "void" && (decl.Body.Count == 0 || !(decl.Body[decl.Body.Count - 1] is ReturnStmt)))
                WriteLine("return default;");
            _indentLevel--;
            WriteLine("}");
        }

        private string FormatParams(FunctionDecl decl)
        {
            bool sawOptional = false;
            var parts = new List<string>();
            foreach (var p in decl.Parameters)
            {
                var t = MapType(string.IsNullOrEmpty(p.Type) || p.Type == "dynamic" ? "dynamic" : p.Type);
                var d = p.DefaultValue != null ? $" = {CompileExpression(p.DefaultValue)}" : null;
                if (d != null) sawOptional = true;
                else if (sawOptional)
                    _warnings.Add($"AOT: '{decl.Name}' — required param '{p.Name}' follows an optional one (C# requires optional last)");
                parts.Add($"{t} {SanitizeName(p.Name)}{d}");
            }
            return string.Join(", ", parts);
        }

        private void CompileClass(ClassDecl decl)
        {
            WriteLine();
            var inheritance = decl.BaseClass != null ? $" : {SanitizeName(decl.BaseClass)}" : "";
            WriteLine($"public class {SanitizeName(decl.Name)}{inheritance}");
            WriteLine("{");
            _indentLevel++;
            var saved = _inClass;
            _inClass = true;

            // `init` becomes a real C# constructor so `new Dog(...)` compiles
            FunctionDecl ctor = null;
            foreach (var m in decl.Members.OfType<FunctionDecl>())
            {
                if (m.Name == "init" || m.Name == "constructor") { ctor = m; break; }
            }

            if (ctor != null)
                CompileConstructor(decl, ctor);

            // operators compile as a group (== / != , < / > pairs must be
            // synthesized together to satisfy C# pairing rules)
            var opDecls = decl.Members.OfType<FunctionDecl>().Where(f => f.IsOperator).ToList();
            if (opDecls.Count > 0)
                CompileOperators(decl, opDecls);

            foreach (var member in decl.Members)
            {
                if (member is FunctionDecl md && ReferenceEquals(md, ctor)) continue;
                if (member is FunctionDecl skipOp && skipOp.IsOperator) continue;
                switch (member)
                {
                    case FunctionDecl f:
                        CompileFunction(f, allowInstance: true);
                        break;
                    case VariableDecl v:
                        CompileField(v);
                        break;
                    case PropertyDecl p:
                        CompileProperty(decl, p);
                        break;
                    case EventDecl e:
                        // plain delegate-typed field: += / -= and invocation all work
                        WriteLine($"public{(e.IsStatic ? " static" : "")} {SanitizeName(e.DelegateType)} {SanitizeName(e.Name)} = null;  // event");
                        break;
                    default:
                        _warnings.Add($"AOT: class '{decl.Name}' member '{member.GetType().Name}' skipped");
                        WriteLine($"// [Nexus AOT] skipped member: {member}");
                        break;
                }
            }

            _inClass = saved;
            _indentLevel--;
            WriteLine("}");
        }

        private void CompileProperty(ClassDecl decl, PropertyDecl p)
        {
            var type = MapType(string.IsNullOrEmpty(p.PropertyType) ? "dynamic" : p.PropertyType);
            var stat = p.IsStatic ? "static " : "";
            WriteLine();
            WriteLine($"public {stat}{type} {SanitizeName(p.Name)}");
            WriteLine("{");
            _indentLevel++;

            if (p.HasGetter)
            {
                if (p.GetterBody != null)
                {
                    WriteLine("get");
                    WriteLine("{");
                    _indentLevel++;
                    foreach (var s in p.GetterBody.Body)
                        CompileStatement(s);
                    if (!p.GetterBody.Body.Any(s => s is ReturnStmt))
                        WriteLine($"return default;");
                    _indentLevel--;
                    WriteLine("}");
                }
                else
                {
                    WriteLine("get;"); // auto getter
                }
            }

            if (p.HasSetter)
            {
                if (p.SetterBody != null)
                {
                    WriteLine("set");
                    WriteLine("{");
                    _indentLevel++;
                    foreach (var s in p.SetterBody.Body)
                        CompileStatement(s);
                    _indentLevel--;
                    WriteLine("}");
                }
                else
                {
                    WriteLine("set;");
                }
            }

            _indentLevel--;
            WriteLine("}");
        }

        /// <summary>Compile operator overloads. Nexus method-style declarations
        /// (`operator +(other)` with 1 param, `operator -()` with 0) become an
        /// instance method `_op_x` plus static C# operator bridges, so bodies
        /// keep using implicit `this`. C#-style 2-param declarations compile
        /// directly. C# requires ==/!=, </>, <=/>= in complete pairs PER
        /// SIGNATURE, so every bridge shape is mirrored on the opposite symbol
        /// when that symbol isn't user-declared.</summary>
        private void CompileOperators(ClassDecl decl, List<FunctionDecl> ops)
        {
            string cn = SanitizeName(decl.Name);
            var present = new HashSet<string>(ops.Select(o => o.OperatorSymbol));

            // (symbol, leftType, rightType, bodyExpr) — rightType null = unary
            var bridges = new List<Tuple<string, string, string, string>>();
            var emittedShapes = new HashSet<string>();

            void AddBridge(string symbol, string left, string right, string expr)
            {
                var key = $"{symbol}|{left}|{right ?? "unary"}";
                if (emittedShapes.Contains(key)) return;
                emittedShapes.Add(key);
                bridges.Add(Tuple.Create(symbol, left, right, expr));
            }

            foreach (var f in ops)
            {
                // equality/comparison operators MUST return bool in C#,
                // regardless of what the Nexus declaration annotated
                var isComparison = f.OperatorSymbol is "==" or "!=" or "<" or ">" or "<=" or ">=";
                var ret = isComparison
                    ? "bool"
                    : string.IsNullOrEmpty(f.ReturnType) ? cn : MapType(f.ReturnType);
                var suffix = OperatorSuffix(f.OperatorSymbol);

                if (f.Parameters.Count == 2)
                {
                    // C# static form — compile directly
                    WriteLine();
                    WriteLine($"public static {ret} operator {f.OperatorSymbol}({FormatParams(f)})");
                    WriteLine("{");
                    _indentLevel++;
                    foreach (var s in f.Body)
                        CompileStatement(s);
                    if (ret != "void" && (f.Body.Count == 0 || !(f.Body[f.Body.Count - 1] is ReturnStmt)))
                        WriteLine("return default;");
                    _indentLevel--;
                    WriteLine("}");

                    var pts = f.Parameters.Select(p =>
                        string.IsNullOrEmpty(p.Type) || p.Type == "dynamic" ? "dynamic" : SanitizeName(p.Type)).ToList();
                    AddBridge(f.OperatorSymbol, pts[0], pts[1], null);
                    continue;
                }

                // method-style: instance method with implicit `this`
                var param = FormatParams(f);   // 1 param (or none for unary)
                WriteLine();
                WriteLine($"public {ret} _op_{suffix}({param})");
                WriteLine("{");
                _indentLevel++;
                foreach (var s in f.Body)
                    CompileStatement(s);
                if (ret != "void" && (f.Body.Count == 0 || !(f.Body[f.Body.Count - 1] is ReturnStmt)))
                    WriteLine("return default;");
                _indentLevel--;
                WriteLine("}");

                WriteLine();
                if (f.Parameters.Count == 1)
                {
                    AddBridge(f.OperatorSymbol, cn, cn, $"a._op_{suffix}(b)");

                    // method-style overloads accept ANY operand (e.g. Vector * 3);
                    // emit mixed-type bridges so C# dynamic dispatch matches
                    var p0 = f.Parameters[0];
                    if (string.IsNullOrEmpty(p0.Type) || p0.Type == "dynamic")
                    {
                        AddBridge(f.OperatorSymbol, cn, "dynamic", $"a._op_{suffix}(b)");
                        AddBridge(f.OperatorSymbol, "dynamic", cn, $"b._op_{suffix}(a)");
                    }
                }
                else
                {
                    WriteLine($"public static {ret} operator {f.OperatorSymbol}({cn} a) => a._op_{suffix}();");
                }
            }

            // pair synthesis per shape: == needs != and vice versa, < >, <= >=
            // (the mirrored body calls the SOURCE symbol's implementation method)
            void Mirror(string symbol, string opposite, string template)
            {
                if (present.Contains(opposite)) return;
                foreach (var b in bridges.Where(b => b.Item1 == symbol).ToList())
                {
                    if (b.Item4 == null) continue;   // body compiled inline (C# static form)
                    var expr = template.Replace("__SUFFIX__", OperatorSuffix(symbol));
                    AddBridge(opposite, b.Item2, b.Item3, expr);
                }
            }

            Mirror("==", "!=", "!(a._op___SUFFIX__(b))");
            Mirror("!=", "==", "!(a._op___SUFFIX__(b))");
            Mirror("<", ">", "b._op___SUFFIX__(a)");
            Mirror(">", "<", "b._op___SUFFIX__(a)");
            Mirror("<=", ">=", "b._op___SUFFIX__(a)");
            Mirror(">=", "<=", "b._op___SUFFIX__(a)");

            // equality operators imply Equals/GetHashCode overrides (C# CS0660/0661)
            if (present.Contains("==") || present.Contains("!="))
            {
                WriteLine();
                WriteLine($"public override bool Equals(object o) => o is {cn} v && this == v;");
                WriteLine($"public override int GetHashCode() => ToString().GetHashCode();");
            }

            // emit all collected bridges (unary + C#-static-form bodies were
            // already emitted inline; they are registered only for mirroring)
            var symbolReturn = new Dictionary<string, string>();
            foreach (var f in ops)
            {
                var isCmp = f.OperatorSymbol is "==" or "!=" or "<" or ">" or "<=" or ">=";
                symbolReturn[f.OperatorSymbol] = isCmp
                    ? "bool"
                    : string.IsNullOrEmpty(f.ReturnType) ? cn : MapType(f.ReturnType);
            }

            foreach (var b in bridges)
            {
                if (b.Item4 == null) continue;   // compiled inline above
                // mirrored (synthesized) symbols are always comparison → bool
                var ret = symbolReturn.TryGetValue(b.Item1, out var declared) ? declared : "bool";
                WriteLine();
                WriteLine($"public static {ret} operator {b.Item1}({b.Item2} a, {b.Item3} b) => {b.Item4};");
            }
        }

        private static string OperatorSuffix(string symbol) => symbol switch
        {
            "+" => "add", "-" => "sub", "*" => "mul", "/" => "div", "%" => "mod",
            "==" => "eq", "!=" => "neq", "<" => "lt", ">" => "gt",
            "<=" => "le", ">=" => "ge", "!" => "not", "~" => "bnot",
            "++" => "inc", "--" => "dec",
            "&" => "band", "|" => "bor", "^" => "bxor",
            "<<" => "shl", ">>" => "shr",
            _ => "op"
        };

        private void CompileConstructor(ClassDecl decl, FunctionDecl ctor)
        {
            // super(args) chains as a C# base-initializer; when the Nexus body
            // omits it but the base ctor requires arguments, chain defaults
            string baseChain = "";
            var superStmt = ctor.Body.OfType<ExpressionStmt>()
                .FirstOrDefault(s => s.Expression is BaseInitCallExpr);
            if (superStmt != null)
            {
                var bse = (BaseInitCallExpr)superStmt.Expression;
                baseChain = $" : base({string.Join(", ", bse.Arguments.Select(CompileExpression))})";
            }
            else if (decl.BaseClass != null &&
                     _classInitParams.TryGetValue(decl.BaseClass, out var baseParams) &&
                     baseParams.Count > 0)
            {
                baseChain = $" : base({string.Join(", ", baseParams.Select(_ => "default"))})";
                _warnings.Add($"AOT: '{decl.Name}' — no super(...) call; chained base ctor with default arguments");
            }

            WriteLine();
            WriteLine($"public {SanitizeName(decl.Name)}({FormatParams(ctor)}){baseChain}");
            WriteLine("{");
            _indentLevel++;
            foreach (var s in ctor.Body)
            {
                if (s is ExpressionStmt { Expression: BaseInitCallExpr })
                    continue;   // became the base-initializer
                CompileStatement(s);
            }
            _indentLevel--;
            WriteLine("}");
        }

        private void CompileStruct(StructDecl decl)
        {
            WriteLine();
            WriteLine($"public class {SanitizeName(decl.Name)}");
            WriteLine("{");
            _indentLevel++;
            var saved = _inClass;
            _inClass = true;
            foreach (var f in decl.Fields.OfType<VariableDecl>())
                CompileField(f);
            _inClass = saved;
            _indentLevel--;
            WriteLine("}");
        }

        private void CompileEnum(EnumDecl decl)
        {
            // Enums compile to a sealed class: members are singleton instances
            // whose ToString() matches the interpreter (`Color.Red`), an implicit
            // int conversion keeps arithmetic and comparisons working, and the
            // member statements become real static members.
            var cn = SanitizeName(decl.Name);
            WriteLine();
            WriteLine($"public sealed class {cn}");
            WriteLine("{");
            _indentLevel++;

            WriteLine("public readonly int Value;");
            WriteLine("private readonly string _memberName;");
            WriteLine();
            WriteLine($"internal {cn}(int value, string memberName) {{ Value = value; _memberName = memberName; }}");

            foreach (var m in decl.Members)
                WriteLine($"public static readonly {cn} {SanitizeName(m.Item1)} = new {cn}({m.Item2}, \"{m.Item1}\");");

            if (decl.Members.Count > 0)
            {
                WriteLine();
                WriteLine($"public override string ToString() => \"{decl.Name}.\" + _memberName;");
                WriteLine($"public static implicit operator int({cn} c) => c.Value;");
            }

            foreach (var member in decl.MemberStatements)
            {
                switch (member)
                {
                    case FunctionDecl f:
                        CompileFunction(f);
                        break;
                    case VariableDecl v:
                    {
                        // enum members are static by construction
                        var type = TypeForDeclaration(v);
                        var init = v.Initializer != null
                            ? $" = {CompileExpression(v.Initializer)}"
                            : " = default";
                        WriteLine($"public static {type} {SanitizeName(v.Name)}{init};");
                        break;
                    }
                    case PropertyDecl p:
                        _warnings.Add($"AOT: enum property '{decl.Name}.{p.Name}' skipped (properties in enums are interpreter/VM-only)");
                        WriteLine($"// [Nexus AOT] skipped enum property: {p}");
                        break;
                    case EventDecl e:
                        WriteLine($"public static {SanitizeName(e.DelegateType)} {SanitizeName(e.Name)} = null;  // event");
                        break;
                }
            }
            _indentLevel--;
            WriteLine("}");
        }

        private void CompileInteropDeclaration(InteropDeclaration decl)
        {
            WriteLine();
            if (decl.InteropType == "DllImport")
            {
                var ps = string.Join(", ", decl.Parameters.Select(p =>
                    $"{MapType(string.IsNullOrEmpty(p.Type) ? "object" : p.Type)} {SanitizeName(p.Name)}"));
                WriteLine($"[System.Runtime.InteropServices.DllImport(\"{decl.Library}\", EntryPoint = \"{decl.EntryPoint ?? decl.MethodName}\")]");
                WriteLine($"public static extern {MapType(decl.ReturnType ?? "int")} {SanitizeName(decl.MethodName)}({ps});");
            }
            else
            {
                WriteLine($"// Interop [{decl.InteropType}] {decl.Library}!{decl.MethodName} (resolved at runtime by Nexus)");
            }
        }

        // ================= asm modules =================

        private void RegisterAsmModule(string varName, AsmBlock block)
        {
            _asmModules[varName] = block.Labels.ToList();
            _asmModuleEntry[varName] = PickEntry(block.Labels);
        }

        private static string PickEntry(IList<string> labels)
        {
            if (labels.Contains("main")) return "main";
            if (labels.Contains("start")) return "start";
            return labels.Count > 0 ? labels[0] : "";
        }

        private void CompileAsmModule(string varName, AsmBlock block)
        {
            if (!_asmModules.ContainsKey(varName))
                RegisterAsmModule(varName, block);

            if (!_asmGenerated.Add(varName))
                return; // already generated

            foreach (var label in block.Labels)
            {
                int start = block.LabelPositions[label];
                int end = block.Instructions.Count;
                foreach (var pos in block.LabelPositions.Values)
                    if (pos > start && pos < end) end = pos;

                WriteLine();
                WriteLine($"// asm module '{varName}' — label '{label}' (jumps can't be transpiled; emitted as comments)");
                WriteLine($"public static long Asm_{SanitizeName(varName)}_{SanitizeName(label)}(long a = 0, long b = 0, long c = 0, long d = 0)");
                WriteLine("{");
                _indentLevel++;
                WriteLine("SetReg(\"ecx\", a); SetReg(\"edx\", b); SetReg(\"ebx\", c); SetReg(\"esi\", d);");
                for (int i = start; i < end; i++)
                    CompileAsmInstruction(block.Instructions[i]);
                WriteLine("return EAX;");
                _indentLevel--;
                WriteLine("}");
            }
        }

        // ================= statements =================

        private void CompileStatement(Statement stmt)
        {
            switch (stmt)
            {
                case VariableDecl vd when vd.Initializer is AsmModuleExpr ame:
                    CompileAsmModule(vd.Name, ame.Block);
                    break;

                case VariableDecl vd when vd.Initializer is LambdaExpr lam:
                {
                    // `var f = (x) => x * 2;` → `Func<dynamic, dynamic> f = x => x * 2;`
                    var ps = string.Join(", ", lam.Parameters.Select(p => $"dynamic {SanitizeName(p.Name)}"));
                    var pl = lam.Parameters.Count == 0 ? "()" : $"({ps})";
                    if (lam.IsExpressionBody)
                    {
                        WriteLine($"{LambdaFuncType(lam)} {SanitizeName(vd.Name)} = {pl} => {CompileExpression(lam.ExpressionBody)};");
                    }
                    else
                    {
                        WriteLine($"{LambdaFuncType(lam)} {SanitizeName(vd.Name)} = {pl} =>");
                        WriteLine("{");
                        _indentLevel++;
                        foreach (var s in lam.Body)
                            CompileStatement(s);
                        if (!lam.Body.Any(s => s is ReturnStmt))
                            WriteLine("return default;");
                        _indentLevel--;
                        WriteLine("};");
                    }
                    break;
                }

                case VariableDecl vd:
                {
                    var isConst = vd.Modifier == "const" && IsCompileTimeConstant(vd.Initializer);
                    var init = vd.Initializer != null
                        ? $" = {CompileExpression(vd.Initializer)}"
                        : " = default";
                    WriteLine($"{(isConst ? "const " : "")}{TypeForDeclaration(vd)} {SanitizeName(vd.Name)}{init};");
                    break;
                }

                case MultiVariableDecl mvd:
                    foreach (var d in mvd.Declarations)
                        CompileStatement(d);
                    break;

                case ExpressionStmt { Expression: BaseInitCallExpr }:
                    _warnings.Add("AOT: 'super(...)' outside a constructor skipped");
                    break;

                case ExpressionStmt es:
                    WriteLine(CompileExpression(es.Expression) + ";");
                    break;

                case PrintStmt ps:
                    CompilePrint(ps);
                    break;

                case BlockStmt bs:
                    WriteLine("{");
                    _indentLevel++;
                    foreach (var s in bs.Statements)
                        CompileStatement(s);
                    _indentLevel--;
                    WriteLine("}");
                    break;

                case IfStmt ifs:
                    WriteLine($"if ({CompileExpression(ifs.Condition)})");
                    CompileBlock(ifs.ThenBranch);
                    if (ifs.ElseBranch != null)
                    {
                        WriteLine("else");
                        CompileBlock(ifs.ElseBranch);
                    }
                    break;

                case WhileStmt ws:
                    if (ws.IsDoWhile)
                    {
                        WriteLine("do");
                        CompileBlock(ws.Body);
                        WriteLine($"while ({CompileExpression(ws.Condition)});");
                    }
                    else
                    {
                        WriteLine($"while ({CompileExpression(ws.Condition)})");
                        CompileBlock(ws.Body);
                    }
                    break;

                case ForStmt fs:
                {
                    string init = "";
                    if (fs.Initializer is VariableDecl fvd)
                        init = $"{TypeForDeclaration(fvd)} {SanitizeName(fvd.Name)}" +
                               (fvd.Initializer != null
                                   ? $" = {CompileExpression(fvd.Initializer)}"
                                   : " = default");
                    else if (fs.Initializer is ExpressionStmt fes)
                        init = CompileExpression(fes.Expression);

                    var cond = fs.Condition != null ? CompileExpression(fs.Condition) : "true";
                    var inc = fs.Increment != null ? CompileExpression(fs.Increment) : "";
                    WriteLine($"for ({init}; {cond}; {inc})");
                    CompileBlock(fs.Body);
                    break;
                }

                case ForeachStmt fes:
                    WriteLine($"foreach (dynamic {SanitizeName(fes.VariableName)} in NexusIterable({CompileExpression(fes.Iterable)}))");
                    CompileBlock(fes.Body);
                    break;

                case ReturnStmt rs:
                    WriteLine(rs.Value != null ? $"return {CompileExpression(rs.Value)};" : "return;");
                    break;

                case BreakStmt:
                    WriteLine(_inSwitchCase ? "// break (case chain handles flow)" : "break;");
                    break;

                case ContinueStmt:
                    WriteLine("continue;");
                    break;

                case ThrowStmt ts:
                    WriteLine($"throw new Exception({(ts.Value != null ? CompileExpression(ts.Value) : "\"error\"")});");
                    break;

                case TryCatchStmt tc:
                    CompileTryCatch(tc);
                    break;

                case SwitchStmt ss:
                    CompileSwitch(ss);
                    break;

                case AsmBlock ab:
                    CompileAsmBlock(ab);
                    break;

                case NamespaceDecl nd:
                    foreach (var s in nd.Body)
                        CompileStatement(s);
                    break;

                case ImportStmt imp:
                    WriteLine($"// import {imp.Module}{(imp.Alias != null ? $" as {imp.Alias}" : "")}");
                    break;

                case FunctionDecl fd:
                    _warnings.Add($"AOT: nested function '{fd.Name}' emitted as local function");
                    CompileLocalFunction(fd);
                    break;

                case ClassDecl cd:
                case EnumDecl ed2:
                case StructDecl sd2:
                    _warnings.Add($"AOT: '{stmt.GetType().Name}' inside a method body is not supported; skipped");
                    WriteLine($"// [Nexus AOT] skipped {stmt} (must be top-level)");
                    break;

                case InteropDeclaration id:
                    CompileInteropDeclaration(id);
                    break;

                default:
                    _warnings.Add($"AOT: unhandled statement '{stmt.GetType().Name}' skipped");
                    WriteLine($"// [Nexus AOT] WARNING: unhandled statement '{stmt.GetType().Name}' skipped");
                    break;
            }
        }

        private string LambdaFuncType(LambdaExpr lam)
        {
            if (lam.Parameters.Count == 0) return $"Func<{InferLambdaReturn(lam)}>";
            var args = string.Join(", ", lam.Parameters.Select(p =>
                string.IsNullOrEmpty(p.Type) || p.Type == "dynamic" ? "dynamic" : MapType(p.Type)));
            return $"Func<{args}, {InferLambdaReturn(lam)}>";
        }

        /// <summary>Best-effort return type for a lambda: long/string/bool/double
        /// when every return statement (or the expression body) is a literal of
        /// that shape, else dynamic. Lets lambdas convert to declared Nexus
        /// delegate types (delegate int Operation(int, int) → Func<long, long, long>).</summary>
        private string InferLambdaReturn(LambdaExpr lam)
        {
            if (lam.IsExpressionBody && lam.ExpressionBody != null)
                return LiteralType(lam.ExpressionBody);

            string inferred = null;
            foreach (var s in lam.Body.OfType<ReturnStmt>())
            {
                if (s.Value == null) return "void";
                var t = LiteralType(s.Value);
                if (t == "dynamic") return "dynamic";
                if (inferred == null) inferred = t;
                else if (inferred != t) return "dynamic";
            }
            return inferred ?? "dynamic";
        }

        private static string LiteralType(Expression e) => e switch
        {
            IntLiteralExpr _ => "long",
            FloatLiteralExpr _ => "double",
            StringLiteralExpr _ => "string",
            BoolLiteralExpr _ => "bool",
            CharLiteralExpr _ => "char",
            _ => "dynamic"
        };

        private void CompileLocalFunction(FunctionDecl decl)
        {
            var ret = string.IsNullOrEmpty(decl.ReturnType) ? "dynamic" : MapType(decl.ReturnType);
            WriteLine($"{ret} {SanitizeName(decl.Name)}({FormatParams(decl)})");
            WriteLine("{");
            _indentLevel++;
            foreach (var s in decl.Body)
                CompileStatement(s);
            _indentLevel--;
            WriteLine("}");
        }

        private void CompilePrint(PrintStmt ps)
        {
            if (ps.Values.Count == 0)
            {
                WriteLine(ps.Newline ? "Console.WriteLine();" : "Console.Write(\"\");");
            }
            else if (ps.Values.Count == 1)
            {
                var call = ps.Newline ? "Console.WriteLine" : "Console.Write";
                WriteLine($"{call}({CompileExpression(ps.Values[0])});");
            }
            else
            {
                var joined = $"string.Join(\" \", {string.Join(", ", ps.Values.Select(CompileExpression))})";
                WriteLine(ps.Newline ? $"Console.WriteLine({joined});" : $"Console.Write({joined});");
            }
        }

        private void CompileBlock(Statement stmt)
        {
            if (stmt is BlockStmt b)
            {
                WriteLine("{");
                _indentLevel++;
                foreach (var s in b.Statements)
                    CompileStatement(s);
                _indentLevel--;
                WriteLine("}");
            }
            else
            {
                _indentLevel++;
                CompileStatement(stmt);
                _indentLevel--;
            }
        }

        private void CompileTryCatch(TryCatchStmt tc)
        {
            WriteLine("try");
            CompileBlock(tc.TryBlock);

            WriteLine("catch (Exception __nexEx)");
            WriteLine("{");
            _indentLevel++;
            if (!string.IsNullOrEmpty(tc.CatchVariable))
                WriteLine($"dynamic {SanitizeName(tc.CatchVariable)} = __nexEx.Message;");
            if (tc.CatchBlock is BlockStmt cb)
            {
                foreach (var s in cb.Statements)
                    CompileStatement(s);
            }
            else if (tc.CatchBlock != null)
            {
                CompileStatement(tc.CatchBlock);
            }
            _indentLevel--;
            WriteLine("}");

            if (tc.FinallyBlock != null)
            {
                WriteLine("finally");
                CompileBlock(tc.FinallyBlock);
            }
        }

        // switch compiles to an if/else chain (works on dynamic values)
        private void CompileSwitch(SwitchStmt ss)
        {
            var subj = CompileExpression(ss.Subject);
            var savedFlag = _inSwitchCase;
            bool first = true;

            foreach (var c in ss.Cases)
            {
                WriteLine($"{(first ? "if" : "else if")} (object.Equals({subj}, {CompileExpression(c.Value)}))");
                WriteLine("{");
                _indentLevel++;
                _inSwitchCase = true;
                foreach (var s in c.Body)
                    CompileStatement(s);
                _indentLevel--;
                WriteLine("}");
                first = false;
            }
            if (ss.DefaultCase != null)
            {
                WriteLine("else");
                CompileBlock(ss.DefaultCase);
            }
            _inSwitchCase = savedFlag;
        }

        private void CompileAsmBlock(AsmBlock block)
        {
            WriteLine("// ---- inline NASM block (simulated registers) ----");
            WriteLine("{");
            _indentLevel++;
            foreach (var inst in block.Instructions)
                CompileAsmInstruction(inst);
            _indentLevel--;
            WriteLine("}");
        }

        private void CompileAsmInstruction(AsmInstruction inst)
        {
            var m = inst.Mnemonic.ToLowerInvariant();
            var op1 = inst.Operand1 ?? "";
            var op2 = inst.Operand2 ?? "";

            switch (m)
            {
                case "mov": WriteLine($"SetReg(\"{op1}\", {RegOrLiteral(op2)}); // mov {op1}, {op2}"); break;
                case "add": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") + {RegOrLiteral(op2)}); // add"); break;
                case "sub": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") - {RegOrLiteral(op2)}); // sub"); break;
                case "mul": WriteLine($"EAX = GetReg(\"{op1}\") * {RegOrLiteral(op2)}; // mul"); break;
                case "div": WriteLine($"EAX = GetReg(\"{op1}\") / Math.Max(1, {RegOrLiteral(op2)}); // div"); break;
                case "inc": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") + 1); // inc {op1}"); break;
                case "dec": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") - 1); // dec {op1}"); break;
                case "cmp": WriteLine($"LastCompare = {RegOrLiteral(op1)}.CompareTo({RegOrLiteral(op2)}); // cmp"); break;
                case "push": WriteLine($"_asmStack.Push({RegOrLiteral(op1)}); // push"); break;
                case "pop": WriteLine($"SetReg(\"{op1}\", _asmStack.Count > 0 ? _asmStack.Pop() : 0); // pop"); break;
                case "and": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") & {RegOrLiteral(op2)}); // and"); break;
                case "or": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") | {RegOrLiteral(op2)}); // or"); break;
                case "xor": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") ^ {RegOrLiteral(op2)}); // xor"); break;
                case "shl": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") << (int){RegOrLiteral(op2)}); // shl"); break;
                case "shr": WriteLine($"SetReg(\"{op1}\", GetReg(\"{op1}\") >> (int){RegOrLiteral(op2)}); // shr"); break;
                case "nop": WriteLine("// nop"); break;
                default:
                    _warnings.Add($"AOT: asm instruction '{inst}' has no C# equivalent; emitted as comment");
                    WriteLine($"// {inst}");
                    break;
            }
        }

        private string RegOrLiteral(string op)
        {
            var lower = (op ?? "").ToLowerInvariant().Trim();
            if (new[] { "eax", "ebx", "ecx", "edx", "esi", "edi", "ebp", "esp" }.Contains(lower))
                return $"GetReg(\"{lower}\")";
            if (long.TryParse(lower, out _))
                return lower + "L";
            return lower.Length > 0 ? lower : "0";
        }

        // ================= expressions =================

        private string CompileExpression(Expression expr)
        {
            switch (expr)
            {
                case IntLiteralExpr ile: return ile.Value + "L";
                case FloatLiteralExpr fle: return fle.Value.ToString("G17");
                case StringLiteralExpr sle: return $"\"{EscapeString(sle.Value)}\"";
                case CharLiteralExpr cle: return $"'{EscapeChar(cle.Value)}'";
                case BoolLiteralExpr ble: return ble.Value ? "true" : "false";
                case NullLiteralExpr _: return "null";
                case IdentifierExpr ie: return SanitizeName(ie.Name);
                case ThisExpr _: return "this";

                case BinaryExpr be when be.Operator == "??":
                    return $"({CompileExpression(be.Left)} ?? {CompileExpression(be.Right)})";

                case BinaryExpr be:
                    if (be.Operator == "/")
                    {
                        // Nexus division is real-valued and throws "Division by zero."
                        // on a zero denominator (matches the interpreter)
                        return $"_div({CompileExpression(be.Left)}, {CompileExpression(be.Right)})";
                    }
                    return $"({CompileExpression(be.Left)} {be.Operator} {CompileExpression(be.Right)})";

                case UnaryExpr ue when ue.IsPostfix:
                    // no parens: `(i++)` is rejected as a statement by C# (CS0201)
                    return $"{CompileExpression(ue.Operand)}{ue.Operator}";
                case UnaryExpr ue:
                    return $"({ue.Operator}({CompileExpression(ue.Operand)}))";

                case AssignExpr ae:
                    return CompileAssignment(ae);

                // asm module call rewrites (checked before the generic call)
                case CallExpr ce when ce.Callee is MemberAccessExpr { Object: IdentifierExpr host } hostCall
                                      && _asmModules.TryGetValue(host.Name, out var lbls)
                                      && lbls.Contains(hostCall.Member):
                    return $"Asm_{SanitizeName(host.Name)}_{SanitizeName(hostCall.Member)}({string.Join(", ", ce.Arguments.Select(CompileExpression))})";

                case CallExpr ce when ce.Callee is IdentifierExpr clsCall
                                      && _classNames.Contains(clsCall.Name):
                    // Nexus constructor-call style: Vector(1, 2) → new Vector(1, 2)
                    return $"new {SanitizeName(clsCall.Name)}({string.Join(", ", ce.Arguments.Select(CompileExpression))})";

                case CallExpr ce when ce.Callee is IdentifierExpr modCall
                                      && _asmModules.ContainsKey(modCall.Name):
                    return $"Asm_{SanitizeName(modCall.Name)}_{SanitizeName(_asmModuleEntry[modCall.Name])}({string.Join(", ", ce.Arguments.Select(CompileExpression))})";

                case CallExpr ce when ce.Callee is IdentifierExpr fname
                                      && _functionSignatures.TryGetValue(fname.Name, out var sigTypes):
                {
                    // delegate-typed parameters get an explicit wrapper around
                    // lambda-typed variables (Func<...> doesn't implicitly
                    // convert to a named delegate type in C#)
                    var args = new List<string>();
                    for (int i = 0; i < ce.Arguments.Count; i++)
                    {
                        var compiled = CompileExpression(ce.Arguments[i]);
                        var sigType = i < sigTypes.Count ? sigTypes[i] : null;
                        if (sigType != null &&
                            _delegateSignatures.TryGetValue(sigType, out var delParams) &&
                            ce.Arguments[i] is IdentifierExpr av &&
                            _lambdaVars.Contains(av.Name))
                        {
                            // Func<...> doesn't implicitly convert to a named
                            // delegate type — forward through a target-typed lambda
                            var names = delParams.Select((_, di) => $"__d{di}").ToList();
                            var dps = string.Join(", ", delParams.Select((t, di) =>
                                $"{(string.IsNullOrEmpty(t) || t == "dynamic" ? "dynamic" : MapType(t))} {names[di]}"));
                            compiled = $"new {SanitizeName(sigType)}(({dps}) => {compiled}({string.Join(", ", names)}))";
                        }
                        args.Add(compiled);
                    }
                    return $"{CompileExpression(ce.Callee)}({string.Join(", ", args)})";
                }

                case CallExpr ce:
                    return $"{CompileExpression(ce.Callee)}({string.Join(", ", ce.Arguments.Select(CompileExpression))})";

                case MemberAccessExpr mae when mae.NullConditional:
                    return $"{CompileExpression(mae.Object)}?.{SanitizeName(mae.Member)}";

                case MemberAccessExpr mae:
                    return $"{CompileExpression(mae.Object)}.{SanitizeName(mae.Member)}";

                case IndexExpr idx:
                    return $"{CompileExpression(idx.Object)}[{CompileExpression(idx.Index)}]";

                case TernaryExpr te:
                    return $"({CompileExpression(te.Condition)} ? {CompileExpression(te.ThenExpr)} : {CompileExpression(te.ElseExpr)})";

                case ListExpr le:
                    return $"new List<dynamic> {{ {string.Join(", ", le.Elements.Select(CompileExpression))} }}";

                case RangeExpr re:
                    return $"_range({CompileExpression(re.Start)}, {CompileExpression(re.End)})";

                case DictExpr de:
                    return $"new Dictionary<dynamic, dynamic> {{ {string.Join(", ", de.Pairs.Select(kv => $"{{ {CompileExpression(kv.Key)}, {CompileExpression(kv.Value)} }}"))} }}";

                case NewExpr ne:
                    return CompileNew(ne);

                case InterpStringExpr ise:
                {
                    // translate directly to a C# interpolated string; literal
                    // braces must be doubled or C# treats them as holes
                    var sb = new StringBuilder();
                    sb.Append("$\"");
                    foreach (var part in ise.Parts)
                    {
                        if (part is Expression inner)
                            sb.Append("{" + CompileExpression(inner) + "}");
                        else
                            sb.Append(EscapeString((part?.ToString() ?? "")
                                .Replace("{", "{{").Replace("}", "}}")));
                    }
                    sb.Append("\"");
                    return sb.ToString();
                }

                case LambdaExpr lam:
                {
                    // emit the lambda source; C# infers the delegate type from
                    // context (event += , delegate-typed vars/params). Block
                    // bodies are valid C# lambda expressions — the statements
                    // are compiled through the normal path and spliced in.
                    var ps2 = string.Join(", ", lam.Parameters.Select(p => SanitizeName(p.Name)));
                    var pl2 = lam.Parameters.Count == 1
                        ? SanitizeName(lam.Parameters[0].Name)
                        : $"({ps2})";
                    if (lam.IsExpressionBody)
                        return $"{pl2} => {CompileExpression(lam.ExpressionBody)}";

                    var lb = new StringBuilder();
                    lb.Append(pl2).Append(" => {");
                    foreach (var s in lam.Body)
                    {
                        int start = _sb.Length;
                        CompileStatement(s);
                        var slice = _sb.ToString(start, _sb.Length - start);
                        _sb.Length = start;   // splice out of the main output
                        lb.Append(' ').Append(slice.TrimEnd());
                    }
                    lb.Append(" }");
                    return lb.ToString();
                }

                case AsExpr ae:
                    return MapType(ae.TargetType) == "dynamic"
                        ? CompileExpression(ae.Expression)
                        : $"(({MapType(ae.TargetType)})({CompileExpression(ae.Expression)}))";

                case IsExpr ise:
                    return MapType(ise.TargetType) == "dynamic"
                        ? "true"
                        : $"({CompileExpression(ise.Expression)} is {MapType(ise.TargetType)})";

                default:
                    return Unsupported(expr);
            }
        }

        private string CompileNew(NewExpr ne)
        {
            var args = string.Join(", ", ne.Arguments.Select(CompileExpression));
            switch (ne.TypeName.ToLowerInvariant())
            {
                case "list":
                case "array":
                    return "new List<dynamic>()";
                case "dict":
                    return "new Dictionary<dynamic, dynamic>()";
                default:
                    return $"new {SanitizeName(ne.TypeName)}({args})";
            }
        }

        private string CompileAssignment(AssignExpr expr)
        {
            var target = CompileExpression(expr.Target);
            var value = CompileExpression(expr.Value);
            return expr.Operator == "=" ? $"{target} = {value}" : $"{target} {expr.Operator} {value}";
        }

        private string Unsupported(Expression expr)
        {
            _warnings.Add($"AOT: expression '{expr.GetType().Name}' ('{expr}') compiled as null");
            return "null";
        }

