        // ================= utilities =================

        private string TypeForDeclaration(VariableDecl vd)
        {
            if (vd.Initializer == null)
                return MapType(string.IsNullOrEmpty(vd.VarType) ? "dynamic" : vd.VarType);

            switch (vd.Initializer)
            {
                case IntLiteralExpr _: return "long";
                case FloatLiteralExpr _: return "double";
                case StringLiteralExpr _: return "string";
                case BoolLiteralExpr _: return "bool";
                case CharLiteralExpr _: return "char";
                default:
                    if (!string.IsNullOrEmpty(vd.VarType) &&
                        vd.VarType != "dynamic" && vd.VarType != "var" && vd.VarType != "let")
                        return MapType(vd.VarType);
                    return "dynamic";
            }
        }

        private static bool IsCompileTimeConstant(Expression e) =>
            e is IntLiteralExpr || e is FloatLiteralExpr || e is StringLiteralExpr
                || e is BoolLiteralExpr || e is CharLiteralExpr;

        private static string MapType(string nexusType)
        {
            switch (nexusType)
            {
                case "int": return "long";
                case "float":
                case "double": return "double";
                case "string": return "string";
                case "char": return "char";
                case "bool":
                case "boolean": return "bool";
                case "void": return "void";
                case "byte": return "byte";
                case "short": return "short";
                case "long": return "long";
                case "uint": return "uint";
                case "ulong": return "ulong";
                case "list": return "List<dynamic>";
                case "dict": return "Dictionary<string, dynamic>";
                case "":
                case "var":
                case "let":
                case "dynamic":
                case "object": return "dynamic";
                default: return nexusType; // user classes pass through
            }
        }

        private static readonly HashSet<string> CSharpKeywords = new HashSet<string>
        {
            "int","float","double","string","bool","char","long","short","byte","object","dynamic",
            "var","void","class","new","this","base","if","else","while","for","foreach","in","do",
            "switch","case","break","continue","return","throw","try","catch","finally","static",
            "public","private","protected","internal","virtual","override","abstract","sealed",
            "async","await","namespace","using","enum","struct","const","ref","out","params",
            "true","false","null","is","as","delegate","event","operator","implicit","explicit",
            "lock","unsafe","fixed","sizeof","typeof","checked","unchecked","goto","default",
            "volatile","partial","where","value","get","set"
        };

        private static string SanitizeName(string name)
        {
            if (string.IsNullOrEmpty(name)) return "_";
            var n = name.Replace("-", "_").Replace(".", "_");
            if (char.IsDigit(n[0])) n = "_" + n;
            return CSharpKeywords.Contains(n) ? "@" + n : n; // e.g. base -> @base, int -> @int
        }

        private static string EscapeString(string s)
        {
            return s.Replace("\\", "\\\\").Replace("\"", "\\\"")
                    .Replace("\n", "\\n").Replace("\t", "\\t").Replace("\r", "\\r");
        }

        private static string EscapeChar(char c)
        {
            switch (c)
            {
                case '\'': return "\\'";
                case '\\': return "\\\\";
                case '\n': return "\\n";
                case '\t': return "\\t";
                case '\r': return "\\r";
                default: return c.ToString();
            }
        }

        private void WriteLine(string text = "")
        {
            if (string.IsNullOrEmpty(text))
            {
                _sb.AppendLine();
                return;
            }
            _sb.AppendLine(new string(' ', _indentLevel * 4) + text);
        }
    }
